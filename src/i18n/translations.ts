export const TRANSLATIONS: Record<Locale, Record<TranslationKey, string>> = {
  en,
  'zh-CN': zhCN,
};

export function translateKey(locale: Locale, key: TranslationKey): string {
  return TRANSLATIONS[locale][key] ?? TRANSLATIONS.en[key];
}

export function translateGrade(locale: Locale, grade: DecisionGrade): string {
  return translateKey(locale, `grade.${grade}` as TranslationKey);
}

export function translateModuleLabel(locale: Locale, mod: DrillModule): string {
  return translateKey(locale, `nav.${mod}` as TranslationKey);
}

export function translatePositionLabel(locale: Locale, pos: Position | 'ALL'): string {
  if (pos === 'ALL') return locale === 'zh-CN' ? '全部位置' : 'All Seats';
  if (locale === 'en') return pos;
  const zhNames: Record<Position, string> = {
    UTG: 'UTG (枪口)',
    HJ: 'HJ (劫持)',
    CO: 'CO (关煞)',
    BTN: 'BTN (按钮)',
    SB: 'SB (小盲)',
    BB: 'BB (大盲)',
  };
  return zhNames[pos];
}

export function translateStreetLabel(locale: Locale, street: Street | 'SHOWDOWN' | string): string {
  const lower = street.toLowerCase();
  if (lower === 'preflop') return translateKey(locale, 'street.preflop');
  if (lower === 'flop') return translateKey(locale, 'street.flop');
  if (lower === 'turn') return translateKey(locale, 'street.turn');
  if (lower === 'river') return translateKey(locale, 'street.river');
  if (lower === 'showdown') return translateKey(locale, 'street.showdown');
  return street;
}

